test('receipt keeps its approved appearance when application theme changes', async ({ page }) => {
  const baseline = JSON.parse(await readFile('outputs/fastwork-preview/baseline.json', 'utf8'))
  for (const language of ['th', 'en']) {
  await page.goto('/app')
  await page.evaluate(value => localStorage.setItem('khonnai-language', value), language)
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', language)
  await page.evaluate(() => {
    document.documentElement.style.setProperty('--ds-ink', '#171717')
    document.documentElement.style.setProperty('--ds-selected', '#f5f5f5')
    document.documentElement.style.setProperty('--ds-font', 'serif')
  })
  const base64 = await page.evaluate(async ({ fixture, shop }) => {
    // @ts-expect-error Vite serves this existing renderer during the browser test.
    const { billImage } = await import('/src/features/BillImage.ts')
    const blob = await billImage(fixture, shop)
    const bytes = new Uint8Array(await blob.arrayBuffer())
    let binary = ''; for (const byte of bytes) binary += String.fromCharCode(byte)
    return btoa(binary)
  }, baseline)
  expect(Buffer.from(base64, 'base64').equals(await readFile('outputs/fastwork-preview/receipt-baseline.png'))).toBe(true)
  }
})

