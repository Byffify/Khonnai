import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const out = 'outputs/landing-start-carousel'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const report = []
for (const width of [1440, 390, 320, 768]) {
  const context = await browser.newContext({ viewport: { width, height: 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5288/d.html#data')
  await page.locator('.start-card').last().waitFor({ state: 'attached' })
  await page.evaluate(() => document.fonts.ready)
  await page.locator('#start-title').scrollIntoViewIfNeeded()
  await page.waitForTimeout(300)
  const viewport = page.locator('.start-viewport')
  assert.equal(await page.locator('.start-card').count(), 3)
  assert(await page.locator('.start-prev').isDisabled())
  assert(await page.locator('.start-next').isEnabled())
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.waitForFunction(() => { const image = document.querySelector('.start-card img'); return image.complete && image.naturalWidth > 0 })
  if ([1440, 390].includes(width)) await page.screenshot({ path: `${out}/initial-${width}.png` })
  await page.locator('.start-next').click()
  await page.waitForTimeout(650)
  assert(await viewport.evaluate(e => e.scrollLeft > 0))
  await viewport.focus()
  await page.keyboard.press('End')
  await page.waitForTimeout(650)
  assert(await page.locator('.start-next').isDisabled())
  await page.waitForFunction(() => [...document.querySelectorAll('.start-card img')].every(i => i.complete && i.naturalWidth > 0))
  assert.equal((await page.locator('.start-position').innerText()).trim(), '3 / 3')
  if ([1440, 390].includes(width)) await page.screenshot({ path: `${out}/last-${width}.png` })
  await page.keyboard.press('Home')
  await page.waitForTimeout(650)
  assert(await page.locator('.start-prev').isDisabled())
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(650)
  assert(await viewport.evaluate(e => e.scrollLeft > 0))
  assert.deepEqual(errors, [])
  report.push({ width, threeSteps: true, imagesLoaded: true, arrowNavigation: true, keyboard: true, noOverflow: true, errors })
  await context.close()
}
const context = await browser.newContext({ viewport: { width: 390, height: 900 }, reducedMotion: 'reduce' })
const page = await context.newPage()
await page.goto('http://127.0.0.1:5288/d.html#data')
await page.locator('.start-next').click()
assert(await page.locator('.start-viewport').evaluate(e => e.scrollLeft > 0))
report.push({ reducedMotion: true, immediateNavigation: true })
await browser.close()
await writeFile(`${out}/verification.json`, JSON.stringify(report, null, 2))
console.log('PASS carousel 320/390/768/1440px: images, arrows, keyboard, overflow, reduced motion')
