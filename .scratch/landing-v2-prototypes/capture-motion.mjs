import { chromium } from '@playwright/test'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
import crypto from 'node:crypto'
const out = 'outputs/landing-motion-prototype'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const results = []
for (const width of [1440, 390, 320, 768]) {
  const context = await browser.newContext({ viewport: { width, height: width < 500 ? 844 : 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:5288/d.html')
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(900)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'no page overflow')
  if (width === 1440 || width === 390) await page.screenshot({ path: `${out}/hero-${width}.png` })
  const marquee = page.locator('[data-marquee]')
  await marquee.scrollIntoViewIfNeeded()
  await page.mouse.move(0, 0)
  await page.waitForTimeout(250)
  assert.equal(await marquee.getAttribute('data-running'), 'true')
  const toggle = page.locator('[data-motion-toggle]')
  await toggle.click()
  assert.equal(await toggle.getAttribute('aria-pressed'), 'true')
  assert.equal(await marquee.getAttribute('data-running'), 'false')
  await toggle.click()
  assert.equal(await toggle.getAttribute('aria-pressed'), 'false')
  await marquee.hover()
  const hoverState = await page.locator('[data-marquee-track]').evaluate(e => getComputedStyle(e).animationPlayState)
  assert.equal(hoverState, 'paused', 'hover pauses moving content')
  const duplicate = page.locator('.cap-duplicate')
  assert.equal(await duplicate.getAttribute('aria-hidden'), 'true')
  assert.equal(await duplicate.evaluate(e => e.inert), true)
  await page.locator('.cap-group:not(.cap-duplicate) .capability').first().focus()
  assert.equal(await page.locator('[data-marquee-track]').evaluate(e => getComputedStyle(e).animationName), 'none', 'keyboard focus stops spatial motion')
  await toggle.focus()
  await page.mouse.move(0, 0)
  if (width === 1440 || width === 390) await page.screenshot({ path: `${out}/carousel-${width}.png` })
  await page.locator('#preview').scrollIntoViewIfNeeded()
  if (width === 1440 || width === 390) await page.screenshot({ path: `${out}/demo-${width}.png` })
  await page.locator('[data-teaser-link="3"]').click()
  await page.waitForTimeout(750)
  assert.equal(await page.locator('[data-teaser-link="3"]').getAttribute('aria-current'), 'step')
  await page.locator('[data-billing="annual"]').click()
  assert.match(await page.locator('[data-price="basic"]').innerText(), /3,229.20/)
  assert.match(await page.locator('[data-price="pro"]').innerText(), /7,549.20/)
  if (width === 1440 || width === 390) {
    await page.waitForTimeout(250)
    await page.locator('#pricing').scrollIntoViewIfNeeded()
    await page.screenshot({ path: `${out}/pricing-${width}.png` })
  }
  await page.locator('[data-billing="monthly"]').click()
  assert.equal((await page.locator('[data-price="basic"]').innerText()).trim(), '299')
  await page.locator('.pricing-action[aria-controls]').first().click()
  assert.equal(await page.locator('.pricing-action[aria-controls]').first().getAttribute('aria-expanded'), 'true')
  await page.locator('.extra-demo > summary').click()
  await page.locator('[data-size="L"]').click()
  await page.locator('[data-color="white"]').click()
  assert.equal((await page.locator('[data-result]').innerText()).trim(), '10')
  await page.locator('[data-sale-replay]').click()
  await page.waitForTimeout(1350)
  assert.equal(await page.locator('[data-step="3"]').evaluate(e => e.classList.contains('current')), true)
  await page.locator('.extra-demo > summary').click()
  assert.deepEqual(await page.evaluate(() => Object.keys(localStorage)), [])
  assert.deepEqual(errors, [])
  results.push({ width, overflow: false, pauseResume: true, hoverPause: hoverState, duplicateHiddenInert: true, teaserLastStep: true, pricingAnnual: [3229.2, 7549.2], pricingMonthly: 299, optionalDemoAfter: 10, saleReplay: true, storage: 'empty', runtimeErrors: errors })
  console.log(`Verified ${width}px`)
  if (width === 1440 || width === 390) {
    await page.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 700) { scrollTo(0, y); await new Promise(r => setTimeout(r, 50)) } scrollTo(0, 0) })
    await page.waitForTimeout(800)
    await page.screenshot({ path: `${out}/full-${width}.png`, fullPage: true })
  }
  await context.close()
}
const reduced = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
const page = await reduced.newPage()
await page.goto('http://127.0.0.1:5288/d.html')
await page.locator('[data-marquee]').scrollIntoViewIfNeeded()
assert.equal(await page.locator('[data-marquee]').getAttribute('data-running'), 'false')
await page.locator('[data-sale-replay]').click()
assert.equal(await page.locator('[data-step="3"]').evaluate(e => e.classList.contains('current')), true)
await page.locator('[data-billing="annual"]').click()
assert.match(await page.locator('[data-price="pro"]').innerText(), /7,549.20/)
results.push({ reducedMotion: true, marqueeRunning: false, saleFinalImmediate: true, pricingWorks: true, activeAnimations: await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length) })
await reduced.close()
const recording = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: `${out}/recordings`, size: { width: 1440, height: 900 } } })
const movie = await recording.newPage()
await movie.goto('http://127.0.0.1:5288/d.html')
await movie.waitForTimeout(1400)
for (let i = 0; i < 6; i++) { await movie.mouse.wheel(0, 220); await movie.waitForTimeout(220) }
await movie.locator('[data-marquee]').scrollIntoViewIfNeeded()
await movie.mouse.move(0, 0)
await movie.waitForTimeout(1600)
await movie.locator('[data-motion-toggle]').click()
await movie.locator('#preview').scrollIntoViewIfNeeded()
for (const step of [0, 1, 2, 3]) { await movie.locator(`#teaser-${step}`).scrollIntoViewIfNeeded(); await movie.waitForTimeout(650) }
await movie.locator('[data-billing="annual"]').click()
await movie.waitForTimeout(1000)
const video = movie.video()
await recording.close()
await video.saveAs(`${out}/motion-tour.webm`)
const snapshot = JSON.parse(await readFile('.scratch/landing-v2-prototypes/production-source-before.json', 'utf8'))
for (const file of snapshot) assert.equal(crypto.createHash('sha256').update(await readFile(file.Path)).digest('hex').toUpperCase(), file.Hash)
results.push({ productionSourceHashesUnchanged: snapshot.length })
await browser.close()
await writeFile(`${out}/verification.json`, JSON.stringify(results, null, 2))
console.log(JSON.stringify(results, null, 2))
